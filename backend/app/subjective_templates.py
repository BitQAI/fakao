def slot_for(subject: str, qtype: str = "case") -> dict:
    """科目 + 题型 → 卷面题号信息；未知科目给一个中性默认值。

    综合大案例横跨民法/民诉/商法，这三科的 EXAM_SLOTS 已统一指向第 4 题；
    论述题与科目无关（只有第 1 题），直接按题型给。
    """
    if qtype == "essay":
        spec = SPECS["essay"]
        return {"slot": spec["slot"], "label": "第1题·法治思想论述",
                "score": spec["score"], "minutes": spec["minutes"]}
    return EXAM_SLOTS.get(subject, {"slot": 0, "label": subject,
                                    "score": 0, "minutes": 0})


def skeleton_for(subject: str, qtype: str = "case") -> list[str]:
    """作答骨架：题型优先（论述题、综合大案例各有一套专用骨架）。"""
    if qtype == "essay":
        return ESSAY_SKELETON
    if qtype == "composite":
        return COMPOSITE_SKELETON
    return SKELETONS.get(subject, [])


def kinds_for(qtype: str = "case") -> tuple[str, ...]:
    """该题型允许的采分点维度。"""
    return ESSAY_KINDS if qtype == "essay" else POINT_KINDS


def kind_order() -> dict[str, int]:
    """维度排序表：论述题与案例分析分属两套维度，合并给一个顺序。"""
    return {k: i for i, k in enumerate(POINT_KINDS + ESSAY_KINDS)}


def spec_for(qtype: str) -> dict:
    """题型形式要求；未知题型回落到案例分析。"""
    return SPECS.get(qtype, SPECS["case"])


def squash(text: str) -> str:
    """去掉空白与标点，只留可比较的字符。

    论述题判「是否照搬材料」、生成脚本回查「材料出处」都走这一套归一，
    避免标点与换行差异造成误判。
    """
    return re.sub(r"[\s\W_]+", "", text or "")


def kind_hint_for(subject: str) -> str:
    return KIND_HINT.get(subject, "结论＋依据＋涵摄")
